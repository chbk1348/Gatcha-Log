/**
 * 인앱 업데이트 로그 정본 — Android(Compose)·iOS(SwiftUI) 공용 단일 소스.
 * 디자인 기준: `GL_MD/06_ChangeLog.html` 목업(히어로·필터칩·featured·마일스톤 타임라인·분류 뱃지).
 *
 * 분류(kind): NEW 신규 / IMP 개선 / FIX 수정 / SEC 보안.
 * 색상은 플랫폼 UI 레이어에서 kind 별로 매핑한다(여기서는 데이터만 보유).
 */
enum class ChangeKind(val key: String, val label: String) {
    NEW("new", "신규"),
    IMP("imp", "개선"),
    FIX("fix", "수정"),
    SEC("sec", "보안"),
}

data class ChangeItem(val kind: ChangeKind, val text: String)

data class ChangeEntry(
    val version: String,
    val date: String,
    val milestone: Boolean = false,
    val featured: Boolean = false,
    val pill: String? = null,        // 예: "첫 출시"
    val securityPill: Boolean = false, // "보안 필수" 강조
    val items: List<ChangeItem>,
) {
    /** 이 릴리스에 포함된 분류 집합(필터칩 매칭용). */
    val kinds: Set<ChangeKind> get() = items.map { it.kind }.toSet()

    /** 항목을 분류 태그 순(신규→개선→수정→보안)으로 정렬해 노출 — 태그 순서 통일. */
    val orderedItems: List<ChangeItem> get() = items.sortedBy { it.kind.ordinal }
}

