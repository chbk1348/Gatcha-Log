package com.gatcha.log.data.api

/**
 * 캐릭터 표시 문구 — **게임이 쓰는 말을 그대로 쓴다.**
 *
 * 세 게임을 한 화면에 담다 보니 원신 어휘로 통일하기 쉬운데, 그러면 그 게임 유저에게는
 * 낯선 말이 된다. 젠레스는 등급을 별로 세지 않고 **S급/A급 에이전트**로 부른다.
 */

/** 등급 표기. 별을 쓰지 않는 게임은 문자열로 돌려준다([usesStars] 로 구분). */
fun rarityLabel(gameKey: String, rarity: Int): String = when (gameKey) {
    "zzz" -> when (rarity) {
        5 -> "S급 에이전트"
        4 -> "A급 에이전트"
        3 -> "B급 에이전트"
        else -> ""
    }
    else -> "★".repeat(rarity.coerceIn(1, 5))
}

/**
 * 짧은 등급 표기 — 필터 칩·목록처럼 자리가 좁은 곳.
 * [rarityLabel] 은 "S급 에이전트"라 칩에 넣기엔 길다.
 */
fun rarityShort(gameKey: String, rarity: Int): String = when (gameKey) {
    "zzz" -> when (rarity) {
        5 -> "S급"
        4 -> "A급"
        3 -> "B급"
        else -> ""
    }
    else -> "${rarity}성"
}

/** 이 게임이 등급을 **별로** 표기하는가. 젠레스만 false. */
fun usesStars(gameKey: String): Boolean = gameKey != "zzz"

/**
 * 이 게임에서 **유물 점수를 쓰는가.**
 *
 * 젠레스는 폐지했다(2026-09-08 지시). 유효 롤 산식이 서는 전제가 약하다 —
 * 직업(`avatar_profession`)을 못 읽으면 유효옵션 판정이 통째로 불가라 점수가 0 이 되고,
 * 폴백으로 치명타를 넘겨짚으면 '이상' 캐릭터에서 거짓 점수가 된다([KeyStatRules] 참고).
 * 틀릴 수 있는 숫자를 화면 중심(링·순위)에 세우느니 **아예 재지 않는다.**
 *
 * false 면 점수·등급·링 게이지·로스터 순위를 **전부 그리지 않는다.**
 */
fun usesArtifactScore(gameKey: String): Boolean = gameKey != "zzz"

/**
 * 특별 배지 — 그 게임에서 **각별한 캐릭터**에게만 붙인다. 없으면 null.
 *
 * - 원신: **일곱신**(집정관)과 **콜롬비나**. 등급(★)만으로는 구분되지 않는 서사적 위치가 있다.
 * - 젠레스: **공허 사냥꾼** 진영. 응답의 `camp`([EnkaChar.camp])로 판정한다.
 *
 * ⚠️ 원신은 이름으로 판정한다. id 가 더 안전하지만 신규 집정관의 id 를 미리 알 수 없고,
 * 이름은 응답이 한국어로 주는 값이라 안정적이다. 새 집정관이 나오면 [GI_ARCHONS] 에 추가한다.
 */
fun specialBadge(gameKey: String, char: EnkaChar): String? = when (gameKey) {
    "genshin" -> GI_REGION_GODS[char.name]?.let { "${it}의 신" }
    "zzz" -> if (char.name in ZZZ_VOID_HUNTERS) "공허 사냥꾼" else null
    else -> null
}

/**
 * 원신에서 **한 지역을 대표하는 신** → 그 지역명. 배지에 "몬드의 신" 처럼 지역을 밝힌다.
 * 그냥 "일곱신" 이라고만 하면 누가 어디의 신인지가 안 남는다.
 *
 * 일곱신(집정관)에 **콜롬비나(노드크라이)** 를 함께 둔다 — 엄밀히는 집정관이 아니지만
 * 그 지역을 대표하는 위치라 배지의 취지는 같다.
 *
 * 새 집정관이 나오면 여기 추가한다.
 */
private val GI_REGION_GODS: Map<String, String> = mapOf(
    "벤티" to "몬드",           // 바르바토스 · 바람
    "종려" to "리월",           // 모락스 · 바위
    "라이덴 쇼군" to "이나즈마",  // 바알 · 번개
    "나히다" to "수메르",        // 부에르 · 풀
    "푸리나" to "폰타인",        // 포칼로스 · 물
    "마비카" to "나타",          // 불
    "츠릉" to "스네즈나야",      // 얼음
    "콜롬비나" to "노드크라이",   // 집정관은 아니지만 그 지역을 대표한다
)

/**
 * 젠레스 **공허 사냥꾼**.
 *
 * ⚠️ 진영(`camp`)으로는 못 가른다. 응답에 "공허 사냥꾼" 이라는 진영은 없고(2026-09-08 실측),
 * 이건 뉴에리두 최고 명예 **칭호**다 — 미야비가 속한 '대공동 특별행동부 제6과'는 그가
 * 과장으로 있는 조직일 뿐이라 야나기·소우카쿠·하루마사는 해당되지 않는다.
 *
 * 새 공허 사냥꾼이 나오면 여기 추가한다.
 */
private val ZZZ_VOID_HUNTERS = setOf(
    "미야비",    // 호시미 미야비 — 칭호 '일심무아', 최초 플레이어블 공허 사냥꾼
    "엽빛나",    // 현세대 공허 사냥꾼
    "레미엘",    // 진영은 '다야트 결사단'
)

/**
 * 캐릭터 **만렙**. 목록의 레벨 막대가 분모로 쓴다.
 *
 * ⚠️ **게임마다 다르다.** 원신 90 · 스타레일 80 · 젠레스 60 — 셋을 같은 값으로 두면
 * 스타레일 만렙 캐릭터가 목록에서 영영 "미완성"으로 보인다(80/90).
 *
 * 돌파 단계별 상한(20/40/50/60/70/80/90)까지는 반영하지 않는다 — 그러면 "만렙인데 돌파를 안 한
 * 상태" 를 또 구분해야 해서 막대 하나가 감당할 정보를 넘는다. 최종 상한만 본다.
 */
fun maxLevelOf(gameKey: String): Int = when (gameKey) {
    "hsr", "starrail" -> 80   // 균형 레벨 6 기준
    "zzz" -> 60               // 인터넷 등급 60 기준
    else -> 90                // 원신 — 모험 등급 55 기준
}
